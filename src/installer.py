# -*- coding: utf-8 -*-
"""
ClickTask - installer.py
Description: User-level desktop integration for ClickTask: a `clicktask`
             launcher in ~/.local/bin, an application-menu entry (so the app is
             found by the desktop search bar), a shortcut on the desktop, the
             app icon and an optional systemd user timer that keeps the install
             updated. No root, no system directories: everything stays under
             $HOME.
Author: JADRT22 (https://github.com/JADRT22)
License: MIT
"""

import argparse
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
from datetime import datetime, timezone

APP_DIR_NAME = "clicktask"
APP_NAME = "ClickTask"
MARKER_FILE = ".clicktask-install"
TIMER_NAME = "clicktask-update"

MANAGED_ENV = "CLICKTASK_PREFIX"


# --- paths ---------------------------------------------------------------


def home():
    return os.path.expanduser("~")


def _xdg(env_name, fallback):
    value = os.environ.get(env_name)
    if value and os.path.isabs(value):
        return value
    return os.path.join(home(), fallback)


def data_home():
    return _xdg("XDG_DATA_HOME", os.path.join(".local", "share"))


def config_home():
    return _xdg("XDG_CONFIG_HOME", ".config")


def default_prefix():
    override = os.environ.get(MANAGED_ENV)
    if override:
        return os.path.expanduser(override)
    return os.path.join(data_home(), APP_DIR_NAME)


def bin_dir():
    override = os.environ.get("CLICKTASK_BIN_DIR")
    if override:
        return os.path.expanduser(override)
    return os.path.join(home(), ".local", "bin")


def applications_dir():
    return os.path.join(data_home(), "applications")


def icons_dir():
    return os.path.join(data_home(), "icons", "hicolor")


def systemd_dir():
    return os.path.join(config_home(), "systemd", "user")


def module_root():
    """The install root that owns this file (…/clicktask/src/installer.py)."""
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def desktop_dir():
    """The user's desktop folder, following XDG (localised names included)."""
    override = os.environ.get("CLICKTASK_DESKTOP_DIR")
    if override:
        return os.path.expanduser(override)
    try:
        result = subprocess.run(
            ["xdg-user-dir", "DESKTOP"], capture_output=True, text=True, timeout=5
        )
        path = result.stdout.strip()
        if result.returncode == 0 and os.path.isabs(path):
            return path
    except (OSError, subprocess.SubprocessError):
        pass
    return os.path.join(home(), "Desktop")


def launcher_path():
    return os.path.join(bin_dir(), APP_DIR_NAME)


def desktop_entry_path():
    return os.path.join(applications_dir(), f"{APP_DIR_NAME}.desktop")


def desktop_shortcut_path():
    return os.path.join(desktop_dir(), f"{APP_NAME}.desktop")


def icon_paths():
    return [
        os.path.join(icons_dir(), "scalable", "apps", f"{APP_DIR_NAME}.svg"),
        os.path.join(icons_dir(), "64x64", "apps", f"{APP_DIR_NAME}.png"),
    ]


def marker_path(prefix):
    return os.path.join(prefix, MARKER_FILE)


# --- file helpers --------------------------------------------------------


def read_version(prefix=None):
    """Read VERSION from a ClickTask tree without importing it."""
    prefix = prefix or module_root()
    path = os.path.join(prefix, "src", "version.py")
    try:
        with open(path, "r", encoding="utf-8") as handle:
            match = re.search(r'^VERSION\s*=\s*"([^"]+)"', handle.read(), re.M)
    except OSError:
        return "0.0.0"
    return match.group(1) if match else "0.0.0"


def _write(path, text, mode=0o644):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = f"{path}.tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.chmod(tmp, mode)
    os.replace(tmp, path)
    return path


def _remove(path):
    try:
        if os.path.isdir(path) and not os.path.islink(path):
            shutil.rmtree(path)
        else:
            os.remove(path)
        return True
    except OSError:
        return False


def _exec_path(path):
    """Quote a path for a .desktop Exec line."""
    escaped = (
        path.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("`", "\\`")
        .replace("$", "\\$")
    )
    return f'"{escaped}"'


# --- generated files -----------------------------------------------------


def launcher_script(prefix):
    return f"""#!/usr/bin/env bash
# ClickTask launcher — generated by the installer; re-run it instead of editing.
set -euo pipefail
APP_DIR={shlex.quote(prefix)}
PY="$APP_DIR/.venv/bin/python"
if [ ! -x "$PY" ]; then
    PY="$(command -v python3 || true)"
fi
if [ -z "$PY" ]; then
    echo "ClickTask: python3 not found" >&2
    exit 1
fi
exec "$PY" "$APP_DIR/src/main.py" "$@"
"""


def desktop_entry(prefix, version=None):
    version = version or read_version(prefix)
    launcher = launcher_path()
    return f"""[Desktop Entry]
Type=Application
Version=1.5
Name={APP_NAME}
GenericName=Auto Clicker
Comment=Interval auto clicker for X11 (GS Auto Clicker model)
Exec={_exec_path(launcher)}
TryExec={_exec_path(launcher)}
Icon={APP_DIR_NAME}
Terminal=false
Categories=Utility;
Keywords=clicker;auto clicker;autoclick;mouse;automation;X11;
StartupNotify=true
StartupWMClass={APP_NAME}
X-ClickTask-Version={version}
"""


def systemd_units(prefix):
    service = f"""[Unit]
Description=ClickTask update check
Documentation=https://github.com/JADRT22/ClickTask

[Service]
Type=oneshot
ExecStart={_exec_path(launcher_path())} update --quiet
"""
    timer = f"""[Unit]
Description=Daily ClickTask release update check

[Timer]
OnCalendar=daily
RandomizedDelaySec=6h
Persistent=true
Unit={TIMER_NAME}.service

[Install]
WantedBy=timers.target
"""
    return {"service": service, "timer": timer}


# --- actions -------------------------------------------------------------


def write_launcher(prefix):
    return _write(launcher_path(), launcher_script(prefix), 0o755)


def write_desktop_entries(prefix, version=None, shortcut=True):
    entry = desktop_entry(prefix, version)
    written = [_write(desktop_entry_path(), entry, 0o755)]
    if shortcut:
        written.append(_write(desktop_shortcut_path(), entry, 0o755))
        _mark_trusted(desktop_shortcut_path())
    return written


def install_icons():
    source_svg = os.path.join(module_root(), "assets", "clicktask.svg")
    source_png = os.path.join(module_root(), "assets", "clicktask.png")
    target_svg, target_png = icon_paths()
    written = []
    for source, target in ((source_svg, target_svg), (source_png, target_png)):
        if not os.path.exists(source):
            continue
        os.makedirs(os.path.dirname(target), exist_ok=True)
        shutil.copyfile(source, target)
        os.chmod(target, 0o644)
        written.append(target)
    return written


def install_autoupdate(prefix=None):
    """Write + enable the daily update timer (best effort, user scope)."""
    units = systemd_units(prefix or module_root())
    written = [
        _write(os.path.join(systemd_dir(), f"{TIMER_NAME}.service"), units["service"]),
        _write(os.path.join(systemd_dir(), f"{TIMER_NAME}.timer"), units["timer"]),
    ]
    _systemctl("daemon-reload")
    _systemctl("enable", "--now", f"{TIMER_NAME}.timer")
    return written


def remove_autoupdate():
    _systemctl("disable", "--now", f"{TIMER_NAME}.timer")
    removed = []
    for suffix in ("service", "timer"):
        path = os.path.join(systemd_dir(), f"{TIMER_NAME}.{suffix}")
        if _remove(path):
            removed.append(path)
    _systemctl("daemon-reload")
    return removed


def read_marker(prefix=None):
    prefix = prefix or module_root()
    try:
        with open(marker_path(prefix), "r", encoding="utf-8") as handle:
            data = json.load(handle)
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def write_marker(prefix, version=None, desktop=True, autoupdate=True):
    data = {
        "name": APP_NAME,
        "prefix": prefix,
        "version": version or read_version(prefix),
        "installed_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "desktop": bool(desktop),
        "autoupdate": bool(autoupdate),
    }
    return _write(marker_path(prefix), json.dumps(data, indent=2) + "\n")


def is_managed(prefix=None):
    """True only for trees created by this installer (auto-update guard)."""
    return os.path.isfile(marker_path(prefix or module_root()))


def install(prefix=None, desktop=True, autoupdate=True, version=None):
    """Create every shortcut for an already-copied tree. Returns created paths."""
    prefix = os.path.abspath(prefix or module_root())
    version = version or read_version(prefix)
    created = {
        "launcher": write_launcher(prefix),
        "desktop_entries": write_desktop_entries(prefix, version, shortcut=desktop),
        "icons": install_icons(),
        "marker": write_marker(prefix, version, desktop=desktop, autoupdate=autoupdate),
        "autoupdate": install_autoupdate(prefix) if autoupdate else remove_autoupdate(),
    }
    refresh_caches()
    return created


def refresh(prefix=None, version=None):
    """Rewrite the shortcuts after an update, keeping the install's choices."""
    prefix = os.path.abspath(prefix or module_root())
    marker = read_marker(prefix)
    version = version or read_version(prefix)
    written = {
        "launcher": write_launcher(prefix),
        "desktop_entries": write_desktop_entries(
            prefix, version, shortcut=bool(marker.get("desktop", True))
        ),
        "icons": install_icons(),
    }
    if is_managed(prefix):
        write_marker(
            prefix,
            version,
            desktop=bool(marker.get("desktop", True)),
            autoupdate=bool(marker.get("autoupdate", True)),
        )
    refresh_caches()
    return written


def uninstall(prefix=None, purge=False):
    """Remove shortcuts, icon and timer. The tree itself is removed by the shell."""
    prefix = os.path.abspath(prefix or module_root())
    removed = []
    for path in [launcher_path(), desktop_entry_path(), desktop_shortcut_path()] + icon_paths():
        if _remove(path):
            removed.append(path)
    removed.extend(remove_autoupdate())
    if _remove(marker_path(prefix)):
        removed.append(marker_path(prefix))
    if purge:
        config_dir = os.path.join(config_home(), APP_DIR_NAME)
        if _remove(config_dir):
            removed.append(config_dir)
    refresh_caches()
    return removed


# --- desktop integration helpers -----------------------------------------


def _mark_trusted(path):
    """Tell the desktop the shortcut is ours, so it runs without a prompt."""
    if not shutil.which("gio"):
        return
    try:
        subprocess.run(
            ["gio", "set", path, "metadata::trusted", "true"],
            capture_output=True,
            timeout=5,
        )
    except (OSError, subprocess.SubprocessError):
        pass


def _systemctl(*args):
    if os.environ.get("CLICKTASK_SKIP_SYSTEMCTL"):
        return False
    if not shutil.which("systemctl"):
        return False
    try:
        result = subprocess.run(
            ["systemctl", "--user", *args], capture_output=True, text=True, timeout=15
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return result.returncode == 0


def refresh_caches():
    """Refresh the menu and icon caches when the tools exist (best effort)."""
    if os.environ.get("CLICKTASK_SKIP_CACHES"):
        return
    commands = []
    if shutil.which("update-desktop-database"):
        commands.append(["update-desktop-database", applications_dir()])
    if shutil.which("gtk-update-icon-cache"):
        commands.append(["gtk-update-icon-cache", "-f", "-t", icons_dir()])
    for command in commands:
        try:
            subprocess.run(command, capture_output=True, timeout=30)
        except (OSError, subprocess.SubprocessError):
            pass


# --- CLI -----------------------------------------------------------------


def build_parser():
    parser = argparse.ArgumentParser(
        prog="installer.py", description="ClickTask desktop integration."
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    install_parser = subparsers.add_parser("install", help="create shortcuts and timer")
    install_parser.add_argument("--prefix", default=None, help="install directory")
    install_parser.add_argument(
        "--no-desktop", action="store_true", help="do not put a shortcut on the desktop"
    )
    install_parser.add_argument(
        "--no-autoupdate", action="store_true", help="do not create the update timer"
    )

    refresh_parser = subparsers.add_parser("refresh", help="rewrite shortcuts in place")
    refresh_parser.add_argument("--prefix", default=None)

    uninstall_parser = subparsers.add_parser("uninstall", help="remove shortcuts and timer")
    uninstall_parser.add_argument("--prefix", default=None)
    uninstall_parser.add_argument(
        "--purge", action="store_true", help="also delete the saved settings"
    )

    status_parser = subparsers.add_parser("status", help="show integration status")
    status_parser.add_argument("--prefix", default=None)

    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    prefix = os.path.abspath(args.prefix or module_root())

    if args.command == "install":
        created = install(
            prefix, desktop=not args.no_desktop, autoupdate=not args.no_autoupdate
        )
        print(f"ClickTask {read_version(prefix)} installed in {prefix}")
        print(f"  launcher : {created['launcher']}")
        for path in created["desktop_entries"]:
            print(f"  shortcut : {path}")
        if created["autoupdate"]:
            print(f"  updates  : daily check ({TIMER_NAME}.timer)")
        print(f"Search for \"{APP_NAME}\" in the application menu to open it.")
        return 0

    if args.command == "refresh":
        written = refresh(prefix)
        print(f"ClickTask {read_version(prefix)} shortcuts refreshed")
        for path in written["desktop_entries"]:
            print(f"  shortcut : {path}")
        return 0

    if args.command == "uninstall":
        removed = uninstall(prefix, purge=args.purge)
        for path in removed:
            print(f"removed {path}")
        return 0

    marker = read_marker(prefix)
    print(f"prefix   : {prefix}")
    print(f"version  : {read_version(prefix)}")
    print(f"managed  : {'yes' if marker else 'no'}")
    print(f"launcher : {'yes' if os.path.exists(launcher_path()) else 'no'}")
    print(f"menu     : {'yes' if os.path.exists(desktop_entry_path()) else 'no'}")
    print(f"desktop  : {'yes' if os.path.exists(desktop_shortcut_path()) else 'no'}")
    timer = os.path.join(systemd_dir(), f"{TIMER_NAME}.timer")
    print(f"timer    : {'yes' if os.path.exists(timer) else 'no'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
